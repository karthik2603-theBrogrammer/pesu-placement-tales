/**
 * Adds admin_reply to feature_requests and bug_reports.
 * Run: node db/migrate-feedback-replies.mjs
 */
import { neon } from "@neondatabase/serverless";
import { readFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));

function loadEnv() {
  try {
    const raw = readFileSync(join(__dirname, "..", ".env"), "utf8");
    for (const line of raw.split("\n")) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) continue;
      const eq = trimmed.indexOf("=");
      if (eq === -1) continue;
      const key = trimmed.slice(0, eq).trim();
      const value = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, "");
      if (!process.env[key]) process.env[key] = value;
    }
  } catch {
    /* .env optional when vars are already exported */
  }
}

loadEnv();

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("DATABASE_URL is not set.");
  process.exit(1);
}

const sql = neon(url);

await sql`
  ALTER TABLE feature_requests
  ADD COLUMN IF NOT EXISTS admin_reply TEXT
`;
console.log("OK: admin_reply on feature_requests");

await sql`
  ALTER TABLE bug_reports
  ADD COLUMN IF NOT EXISTS admin_reply TEXT
`;
console.log("OK: admin_reply on bug_reports");

console.log("Feedback reply migration complete.");
